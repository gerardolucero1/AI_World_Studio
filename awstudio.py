#!/usr/bin/env python
"""AI World Studio command line.

  python awstudio.py ui                                  open the desktop editor
  python awstudio.py generate highland_lake --size 1536 --seed 1 --save World.awp --godot-project ~/proj/godot
  python awstudio.py export World.awp --godot-project ~/proj/godot        (or --out /empty/folder for a standalone project)
  python awstudio.py relocate <package folder> --prefix res://addons/my_world/    (change where the package lives inside a Godot project)
  python awstudio.py tools                               list the semantic tools (same ones the MCP server / REST API expose)
  python awstudio.py call create_mountain '{"x":300,"y":300,"radius":120,"height":60}' --world World.awp --save World.awp
  python awstudio.py mcp | api                           start the MCP server (stdio) / REST API (uvicorn)
  python awstudio.py docs                                regenerate docs/TOOLS.md
"""
from __future__ import annotations

import argparse
import inspect
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))


def _print(d) -> None:
    print(json.dumps(d, indent=2, default=str))


def cmd_generate(a) -> int:
    from core.world import service as S
    r = S.generate_landscape(a.preset, a.size, a.seed)
    _print({k: v for k, v in r.items() if k != "steps"})
    if not r["ok"]:
        return 1
    v = S.validate_world(); print(f"validation: {v['counts']}")
    if a.save:
        _print(S.save_world(a.save))
    if a.godot_project or a.out:
        e = S.export_to_godot(path=a.out, godot_project=a.godot_project, subfolder=a.subfolder, verify=a.verify, profile=a.profile, include_preview=not a.no_preview, navigation=a.navigation, grass=not a.no_grass, terrain=a.terrain, terrain3d_addon=a.terrain3d_addon)
        _print({k: v for k, v in e.items() if k != "validation"}); return 0 if e["ok"] else 1
    return 0


def cmd_export(a) -> int:
    from core.world import service as S
    r = S.load_world(a.world)
    if not r["ok"]:
        _print(r); return 1
    e = S.export_to_godot(path=a.out, godot_project=a.godot_project, subfolder=a.subfolder, verify=a.verify, profile=a.profile, include_preview=not a.no_preview, navigation=a.navigation, grass=not a.no_grass, terrain=a.terrain, terrain3d_addon=a.terrain3d_addon)
    _print({k: v for k, v in e.items() if k != "validation"}); return 0 if e["ok"] else 1


def cmd_relocate(a) -> int:
    from exporters.godot.exporter import relocate_package
    _print(relocate_package(a.package, a.prefix)); return 0


def cmd_tools(a) -> int:
    from core.world import service as S
    for f in S.TOOLS:
        doc = (inspect.getdoc(f) or "").splitlines()[0]
        print(f"{f.__name__:28s} {doc}")
    return 0


def cmd_call(a) -> int:
    from core.world import service as S
    by = {f.__name__: f for f in S.TOOLS}
    if a.tool not in by:
        print(f"unknown tool {a.tool!r}; run `awstudio.py tools`"); return 2
    if a.world:
        S.load_world(a.world)
    r = by[a.tool](**json.loads(a.args or "{}"))
    _print(r)
    if a.save:
        _print(S.save_world(a.save))
    return 0 if r.get("ok", True) else 1


def cmd_docs(a) -> int:
    from core.world import service as S
    lines = ["# Tool reference", "", "Generated by `python awstudio.py docs`. Same tools over MCP (`python -m mcp_server.server`), REST (`uvicorn api.app:app`) and the CLI (`awstudio.py call`).",
             "Units: meters; origin north-west; x east, y south.", ""]
    for f in S.TOOLS:
        lines += [f"## `{f.__name__}{inspect.signature(f)}`", "", inspect.getdoc(f) or "", ""]
    out = ROOT / "docs/TOOLS.md"; out.write_text("\n".join(lines)); print(f"wrote {out} ({len(S.TOOLS)} tools)")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(prog="awstudio", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("ui").set_defaults(fn=lambda a: __import__("app.main", fromlist=["main"]).main())
    g = sub.add_parser("generate"); g.add_argument("preset", nargs="?", default="highland_lake")
    g.add_argument("--size", type=float, default=1536.0); g.add_argument("--seed", type=int, default=1); g.add_argument("--save")
    for p in (g,):
        p.add_argument("--godot-project"); p.add_argument("--out"); p.add_argument("--subfolder", default="GodotWorld"); p.add_argument("--verify", action="store_true")
        p.add_argument("--profile", choices=["full", "compatible"], default="full", help="compatible = also runs on the Compatibility renderer"); p.add_argument("--no-preview", action="store_true"); p.add_argument("--navigation", choices=["auto", "bake", "python", "none"], default="auto"); p.add_argument("--no-grass", action="store_true")
        p.add_argument("--terrain", choices=["mesh", "terrain3d"], default="mesh", help="terrain3d = Terrain3D node + regions (needs the addon)"); p.add_argument("--terrain3d-addon")
    g.set_defaults(fn=cmd_generate)
    e = sub.add_parser("export"); e.add_argument("world"); e.add_argument("--godot-project"); e.add_argument("--out")
    e.add_argument("--subfolder", default="GodotWorld"); e.add_argument("--verify", action="store_true")
    e.add_argument("--profile", choices=["full", "compatible"], default="full"); e.add_argument("--no-preview", action="store_true"); e.add_argument("--navigation", choices=["auto", "bake", "python", "none"], default="auto"); e.add_argument("--no-grass", action="store_true")
    e.add_argument("--terrain", choices=["mesh", "terrain3d"], default="mesh"); e.add_argument("--terrain3d-addon"); e.set_defaults(fn=cmd_export)
    r = sub.add_parser("relocate"); r.add_argument("package"); r.add_argument("--prefix", required=True); r.set_defaults(fn=cmd_relocate)
    sub.add_parser("tools").set_defaults(fn=cmd_tools)
    c = sub.add_parser("call"); c.add_argument("tool"); c.add_argument("args", nargs="?"); c.add_argument("--world"); c.add_argument("--save"); c.set_defaults(fn=cmd_call)
    sub.add_parser("docs").set_defaults(fn=cmd_docs)
    sub.add_parser("mcp").set_defaults(fn=lambda a: __import__("mcp_server.server", fromlist=["mcp"]).mcp.run("stdio"))
    sub.add_parser("api").set_defaults(fn=lambda a: __import__("uvicorn").run("api.app:app", host="127.0.0.1", port=8000))
    a = ap.parse_args()
    return int(a.fn(a) or 0)


if __name__ == "__main__":
    raise SystemExit(main())
